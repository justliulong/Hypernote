const Icons = {
  /** 生成 SVG 字符串 */
  svg(name, cls = 'icon') {
    const inner = ICONS[name];
    if (!inner) return '';
    return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
           `stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
  },

  /** 生成 SVG DOM 节点 */
  el(name, cls = 'icon') {
    const wrap = document.createElement('span');
    wrap.className = 'icon-wrap';
    wrap.style.display = 'contents';
    wrap.innerHTML = this.svg(name, cls);
    return wrap.firstElementChild || document.createTextNode('');
  },

  /** 把容器内所有 [data-icon] 占位元素替换成图标，[data-logo] 替换成品牌标 */
  hydrate(root = document) {
    root.querySelectorAll('[data-icon]').forEach((node) => {
      const svg = this.svg(node.dataset.icon, node.dataset.iconClass || 'icon');
      if (svg) node.innerHTML = svg;
    });
    root.querySelectorAll('[data-logo]').forEach((node) => {
      node.innerHTML = Logo.svg();
    });
  },
};

